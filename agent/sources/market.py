def hardtech_filter(name: str, allow: list[str], exclude: list[str]) -> bool:
    return contains_any(name, allow) and not contains_any(name, exclude)


def build_demo_hotspots(config: dict) -> list[Hotspot]:
    sectors = config.get("default_demo_sectors", [])
    hotspots: list[Hotspot] = []
    for idx, sector in enumerate(sectors, start=1):
        hotspots.append(
            Hotspot(
                rank=idx,
                name=sector,
                primary_industry=_industry_for(sector),
                change_pct="待采集",
                limit_up_count="待采集",
                net_inflow_100m="待采集",
                score=max(60, 96 - idx * 3),
                catalyst=DEMO_CATALYSTS.get(sector, "待接入实时行情和新闻源后补充催化逻辑。"),
                leaders=DEMO_TARGETS.get(sector, []),
                chain_notes=_chain_notes_for(sector),
                subtopics=DEMO_SUBTOPICS.get(sector, []),
            )
        )
    return hotspots


def _chain_notes_for(sector: str) -> str:
    if any(x in sector for x in ("芯片", "封装", "半导体", "光模块", "算力")):
        return "上游：设备/材料/核心器件；中游：芯片、封装、模块与服务器；下游：云计算、数据中心和终端客户。"
    if any(x in sector for x in ("电池", "储能")):
        return "上游：锂、正负极和电解质材料；中游：电芯、PACK、PCS；下游：储能电站、汽车和工商业用户。"
    if any(x in sector for x in ("机器人", "制造", "自动驾驶", "低空")):
        return "上游：传感器、控制器和核心零部件；中游：整机、软件与系统集成；下游：工厂、物流、汽车和城市空域。"
    if any(x in sector for x in ("材料", "散热")):
        return "上游：基础材料与设备；中游：功能材料、热管理和工艺服务；下游：半导体、通信、电池和高端制造。"
    return "上游：核心器件与基础材料；中游：技术产品与系统集成；下游：行业客户和基础设施场景。"


def _industry_for(sector: str) -> str:
    if any(x in sector for x in ("芯片", "封装", "算力", "存储", "半导体")):
        return "TMT/半导体"
    if any(x in sector for x in ("电池", "储能", "新能源")):
        return "新能源"
    if any(x in sector for x in ("机器人", "制造", "低空")):
        return "高端制造"
    if "材料" in sector or "散热" in sector:
        return "新材料"
    return "硬科技"


