const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {PNG}=require('pngjs');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',args:['--enable-unsafe-swiftshader']});
 const output={};
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[],failures=[];page.on('pageerror',e=>errors.push(e.message));page.on('requestfailed',r=>failures.push(r.url()));
  await page.goto('http://127.0.0.1:4173/#contacts');
  await page.locator('#contact-industry-tags button').first().waitFor();
  await page.waitForFunction(()=>document.querySelector('#contact-industry-filter').options.length>2);
  assert.equal(await page.locator('.side-nav a[href="#industries"]').count(),0);
  assert.equal(await page.locator('.contact-legacy').isVisible(),false);
  const stages=await page.locator('.funnel-stage-summary strong').allTextContents();
  const model=await import('../web/workspace_model.mjs');
  const site=JSON.parse(fs.readFileSync('web/data/site_data.json','utf8'));
  const counts=stages.map(s=>Number.parseInt(s));assert.equal(counts[0],model.contactsModel(site.contact_progress?.rows||[]).length);
  assert.ok(counts.every((n,i)=>i===0||n<=counts[i-1]));output.funnel=counts;
  await page.locator('#contact-industry-tags button[data-industry="金刚石散热"]').click();
  assert.equal(await page.locator('#contact-industry-filter').inputValue(),'金刚石散热');
  assert.match(await page.locator('#contact-funnel-meta').textContent(),/19 家公司/);
  await page.screenshot({path:'runs/contact-funnel-desktop.png'});
  await page.locator('#contact-industry-filter').selectOption('玻璃基板');
  assert.equal(await page.locator('#contact-funnel-title').textContent(),'玻璃基板');
  assert.match(await page.locator('#contact-funnel-note').textContent(),/未记录/);
  await page.locator('.side-nav a[href="#topic-network"]').click();
  await page.waitForFunction(()=>document.querySelector('#network-canvas').dataset.renderer==='three');
  await page.waitForFunction(()=>Number(document.querySelector('#network-canvas').dataset.frames)>10);
  const canvas=page.locator('#network-canvas canvas');
  const a=PNG.sync.read(await canvas.screenshot());await page.waitForTimeout(350);const b=PNG.sync.read(await canvas.screenshot());
  let changes=0,drawn=0;
  for(let i=0;i<a.data.length;i+=4){if(a.data[i]!==a.data[0]||a.data[i+1]!==a.data[1]||a.data[i+2]!==a.data[2])drawn++;if(Math.abs(a.data[i]-b.data[i])+Math.abs(a.data[i+1]-b.data[i+1])+Math.abs(a.data[i+2]-b.data[i+2])>10)changes++;}
  assert.ok(drawn>800,'canvas must contain rendered geometry');assert.ok(changes>40,'sphere must move');
  output.canvas={drawn,changes};
  await page.locator('#network-motion').click();
  assert.equal(await page.locator('#network-motion').getAttribute('aria-pressed'),'true');
  await page.screenshot({path:'runs/topic-sphere-desktop.png'});
  const first=page.locator('#network-list button').first();const topic=await first.getAttribute('data-network-topic');
  await first.click();await page.waitForFunction(()=>document.querySelector('#topic-network').dataset.mode==='companies');
  const companyCount=Number(await page.locator('#topic-network').getAttribute('data-company-count'));
  assert.equal(await page.locator('#network-list button[data-network-company]').count(),companyCount);
  await page.locator('#network-list button').first().click();
  assert.match(await page.locator('#network-selection').textContent(),/来源/);
  await page.screenshot({path:'runs/company-network-desktop.png'});output.topic={name:topic,companyCount};
  await page.locator('#network-search').fill('没有这个公司XYZ');assert.match(await page.locator('#network-list').textContent(),/没有匹配/);
  await page.locator('#network-home').click();
  assert.equal(await page.locator('#topic-network').getAttribute('data-mode'),'themes');
  await page.locator('#network-list button[data-network-topic="玻璃基板"]').click();
  await page.locator('.network-detail-link').click();
  await page.waitForFunction(()=>document.querySelector('#primary-mappings.active .mapping-sector-card.active')?.dataset.title==='玻璃基板');
  await page.locator('.side-nav a[href="#topic-network"]').click();
  await page.locator('#network-home').click();
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(500);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'runs/topic-sphere-mobile.png'});
  await page.locator('#network-list button').first().click();await page.waitForTimeout(500);
  await page.screenshot({path:'runs/company-network-mobile.png'});
  await page.emulateMedia({reducedMotion:'reduce'});await page.locator('#network-home').click();
  assert.equal(await page.locator('#network-motion').getAttribute('aria-pressed'),'true');
  await page.goto('http://127.0.0.1:4173/#industries');
  await page.locator('#contacts.active').waitFor();assert.equal(await page.locator('#industries').isVisible(),false);
  assert.deepEqual(errors,[]);assert.deepEqual(failures,[]);
  const fallback=await browser.newPage();
  await fallback.addInitScript(()=>{const get=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return /webgl/i.test(type)?null:get.call(this,type,...args);};});
  await fallback.goto('http://127.0.0.1:4173/#topic-network');
  await fallback.waitForFunction(()=>document.querySelector('#network-canvas').dataset.renderer==='fallback');
  await fallback.locator('#network-list button').first().click();
  assert.ok(await fallback.locator('#network-list button[data-network-company]').count()>0);
  output.fallback='PASS';fs.writeFileSync('runs/atlas_ui_checks.json',JSON.stringify(output,null,2));
  console.log(JSON.stringify(output));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
